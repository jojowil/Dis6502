// A Sample hexdump (https://programmingby.design/algorithms/the-hex-dump/)
static void hexDump(const unsigned char* bytes, long length) {
    // we and with 0xff to mask off the bits when sign-extended.
    int st = bytes[1] * 256 + bytes[0];
    printf("%d\n", st);
    int pc = st, c = 0, x;
    char chars[10] = {0};

    for (x = 2; x < length; x++) {
        // make it pretty
        if ( (pc - st) % 8 == 0 ) {
            // chars are built during each iteration, but
            // printed when we reach the end of the line.
            printf(" %s", chars);
            printf("\n%04X:", pc);
            c = 0;
        }
        unsigned char ch = bytes[x];
        // build the chars - only printable chars
        chars[c++] = ( ch >= 32 && ch <= 127 ) ? ch : '.';

        printf(" %02X", bytes[x]);
        pc++;
    }

    // fix final row
    int last = (pc - st) % 8;
    chars[c] = '\0';
    if (last > 0)
        for (x = 0; x < 8-last; x++)
            printf("   ");
    printf(" %s\n", chars);
}

// Perform disassembly without labels or synchronizing. MOS 6502 only!
static void disassemble (const unsigned char* bytes, int len, int pass) {
    // we and with 0xff (an int) to avoid sign extension
    // and preserve the unsigned nature of the value.
    int pc = (bytes[1] & 0xff) * 256 + (bytes[0] & 0xff);
    int row, col=0;

    for ( int x = 2; x < len; x++ ) {
        // fix the sign!
        int op = bytes[x] & 0xff;
        char* opstr;
        // debug
        // printf("op = %d\n", op);

        // find the matching opcode in Opcodes
        for (row = 0; row < opcodeRows-1; row++)
            for (col = 1; row < opcodeRows-1 && col < opcodeCols; col++) {
                // skip the 0xffs!
                if (opcodeTable[row].opcodes[col] == 0xff)
                    continue;
                // debug
                // printf("row %d, col %d, val %d\n", row, col, (int)Opcodes[row][col]);
                if ( opcodeTable[row].opcodes[col] == op ) {
                    // printf("Found it!\n");
                    goto found; // yeah, it's a goto. Locking in the row/col values.
                }
            }
        found:
        // debug
        //printf("%d(%2X) found at %d,%d.\n", op, op, row, col);
        opstr = opcodeTable[row].mnemonic;

        // need at least one more byte. if we don't have enough to finish the op
        // then we'll display individual bytes.
        if ( (x+2 == len && col != 11) ||
                ( x+3 == len && (col >= 5 && col <= 8) ) ) {
            for ( ; x < len; x++ ) {
                op = bytes[x] & 0xff;
                if ( pass == 2 )
                    printf("%04X:   %02X         %3s\n", pc++, op, "???");
            }
            break;
        }

        // build a real line of output based on addressing mode
        char output[100];
        switch (col) {
            // Imm, 1
            case 1 :
                int imm = bytes[++x] & 0xff;
                snprintf(output, sizeof output, "%04X:   %02X %02X      %3s #$%02X", pc, op, imm, opstr, imm);
                pc += 2;
                break;

            // ZP, 2
            // ZPX, 3
            // ZPY, 4
            case 2: case 3: case 4:
                int zp = bytes[++x] & 0xff;
                char *end = "";
                switch (col) {
                    case 3:
                        end = ",X"; break;
                    case 4:
                        end = ",Y"; break;
                }
                snprintf(output, sizeof output, "%04X:   %02X %02X      %3s $%02X%s", pc, op, zp, opstr, zp, end);
                pc += 2;
                break;

            // ABS, 5
            // ABSX, 6
            // ABSY, 7
            case 5: case 6: case 7:
                int lo = bytes[++x] & 0xff;
                int hi = bytes[++x] & 0xff;
                int addr = hi * 256 + lo;
                end = "";
                switch (col) {
                    case 6:
                        end = ",X"; break;
                    case 7:
                        end = ",Y"; break;
                }
                snprintf(output, sizeof output, "%04X:   %02X %02X %02X   %3s $%04X%s", pc, op, lo, hi, opstr, addr, end);
                pc += 3;
                break;

            // IND, 8
            // INDX, 9
            // INDY, 10
            case 8: case 9: case 10:
                zp = bytes[++x] & 0xff;
                switch (col) {
                    case 9:
                        end = ",X)"; break;
                    case 10:
                        end = "),Y"; break;
                    default:
                        end = ")"; break;
                }
                snprintf(output, sizeof output,"%04X:   %02X %02X      %3s ($%02X%s", pc, op, zp, opstr, zp, end);
                pc += 2;
                break;

            // BRA 12
            case 12:
                int offraw = bytes[++x];
                int off = bytes[x] & 0xff;
                int dst = pc + offraw + 2;
                char *dest = "UNKNOWN!";
                /*
                if ( pass == 1 )
                    labels.put(dst, "label"+labelNum++);
                else
                    dest = labels.get(dst);
                */
                snprintf(output, sizeof output, "%04X:   %02X %02X      %3s $%04X", pc, op, off, opstr, dst);
                //String out = String.format("%04X:   %02X %02X      %3s %s", pc, op, off, opstr, dest);
                pc += 2;
                break;

            // SNGL, 11
            // also bad instructions
            default:
                snprintf(output, sizeof output, "%04X:   %02X         %3s", pc, op, opstr);
                pc += 1;
                break;
        }
        // Todo: implement second pass to introduce labels alongside addresses.
        if ( pass == 2 )
            printf("%s\n", output);
    }
}

// Read a complete file into memory.
char* readAllBytes(const char* fname, long *len) {
    // open file
    FILE *file = fopen(fname, "r");
    if (file == NULL) {
        perror("Error opening source file");
        return NULL;
    }

    // get size
    fseek(file, 0, SEEK_END);
    long fileSize = ftell(file);
    rewind(file);

    // get the mem
    char *buffer = (char *) malloc(fileSize * sizeof(char) + 1);

    // Read the entire file into the buffer
    size_t bytesRead = fread(buffer, 1, fileSize, file);
    if (bytesRead != fileSize) {
        perror("Error reading file");
        fclose(file);
        free(buffer);
        *len = 0;
        return NULL;
    }
    // add the terminator
    buffer[fileSize] = '\0';
    *len = fileSize; // be sure to note the size!
    return buffer;
}

int main(int argc, char ** argv) {

    // check for program file
    if (argc != 2) {
        printf("\nMust provide source.\n\n");
        exit(3);
    }

    // Read file contents
    int flen;
    unsigned char* file = readAllBytes(argv[1], &flen);

    // Display our findings
    hexDump(file, flen);
    printf("\n");
    disassemble(file, flen, 1);
    disassemble(file, flen, 2);
    free(file);
}
